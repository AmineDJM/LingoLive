/**
 * `as const` gives the English dictionary literal types, which is what makes
 * `MessageKey` autocomplete. Translations must match the *shape*, not the
 * English text, so the literals are widened back to `string` here.
 */
type WidenStrings<T> = {
  [K in keyof T]: T[K] extends string ? string : WidenStrings<T[K]>;
};

export type Messages = WidenStrings<typeof en>;
